//go:build integration

package postgres_test

import (
	"context"
	"net"
	"strconv"
	"testing"

	"github.com/testcontainers/testcontainers-go"
	tcpostgres "github.com/testcontainers/testcontainers-go/modules/postgres"

	"github.com/shepherd-yun/sqlvim/internal/db"
	"github.com/shepherd-yun/sqlvim/internal/db/dbtest"
	"github.com/shepherd-yun/sqlvim/internal/db/postgres"
	"github.com/shepherd-yun/sqlvim/internal/sqlx"
)

var fixture = []string{
	`CREATE SCHEMA app`,
	`CREATE TABLE app.users (id bigint PRIMARY KEY, name text NOT NULL, email text, note text DEFAULT 'hi')`,
	`COMMENT ON COLUMN app.users.name IS 'display name'`,
	`CREATE UNIQUE INDEX users_email_key ON app.users (email)`,
	`CREATE TABLE app.orders (id bigint PRIMARY KEY, user_id bigint NOT NULL,
	   CONSTRAINT orders_user_fk FOREIGN KEY (user_id) REFERENCES app.users (id))`,
	`CREATE TABLE app."order" (id int)`,
	`CREATE TABLE app."MixedCase" (id int)`,
	`CREATE VIEW app.active_users AS SELECT id, name FROM app.users`,
	`CREATE FUNCTION app.add_one(x int) RETURNS int LANGUAGE sql AS 'SELECT x + 1'`,
	`INSERT INTO app.users VALUES (1, 'alice', 'a@x.com', DEFAULT), (2, '李雷', '', NULL), (3, 'bob', NULL, E'multi\nline')`,
}

func TestContract(t *testing.T) {
	ctx := context.Background()
	const password = "p@ss:w/rd?#%"
	ctr, err := tcpostgres.Run(ctx, "postgres:16-alpine",
		tcpostgres.WithDatabase("app"),
		tcpostgres.WithUsername("sqlvim"),
		tcpostgres.WithPassword(password),
		tcpostgres.BasicWaitStrategies(),
	)
	testcontainers.CleanupContainer(t, ctr)
	if err != nil {
		t.Fatal(err)
	}
	endpoint, err := ctr.PortEndpoint(ctx, "5432/tcp", "")
	if err != nil {
		t.Fatal(err)
	}
	host, portStr, _ := net.SplitHostPort(endpoint)
	port, _ := strconv.Atoi(portStr)

	conn, err := postgres.Driver{}.Open(ctx, db.ConnConfig{
		Host: host, Port: port, User: "sqlvim", Password: password, Database: "app",
		Params: map[string]string{"sslmode": "disable"},
	})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = conn.Close() })

	for _, stmt := range fixture {
		if _, err := conn.Exec(ctx, stmt); err != nil {
			t.Fatalf("fixture %q: %v", stmt, err)
		}
	}
	open := func(ctx context.Context, readOnly bool) (db.Conn, error) {
		return postgres.Driver{}.Open(ctx, db.ConnConfig{
			Host: host, Port: port, User: "sqlvim", Password: password, Database: "app",
			Params: map[string]string{"sslmode": "disable"}, ReadOnly: readOnly,
		})
	}
	dbtest.RunContract(t, conn, dbtest.Fixture{
		Dialect:      sqlx.Postgres,
		NVarcharSQL:  []string{`CREATE TABLE app.uni (id int PRIMARY KEY, name text)`},
		NS:           db.Namespace{Database: "app", Schema: "app"},
		SleepSQL:     "SELECT pg_sleep(30)",
		ManyRowsSQL:  "SELECT generate_series(1, 30000000)",
		OpenReadOnly: func(ctx context.Context) (db.Conn, error) { return open(ctx, true) },
		NormTypesSQL: []string{
			`CREATE TABLE app.norm_types (id serial PRIMARY KEY, n integer NOT NULL DEFAULT 0, flag boolean,
					   name character varying(20) DEFAULT 'x', created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
					   big bigint, price numeric(10,2), body text, ci varchar(10) COLLATE "C",
					   ident int GENERATED BY DEFAULT AS IDENTITY)`,
			`COMMENT ON TABLE app.norm_types IS 'normalized'`,
		},
		NormTypes: map[string]string{
			"id": "int", "n": "int", "flag": "bool", "name": "varchar(20)", "created_at": "timestamptz",
			"big": "bigint", "price": "numeric(10,2)", "body": "text", "ci": "varchar(10)", "ident": "int",
		},
		AutoIncrement: []string{"id", "ident"},
		CICollation:   "C",
		CompareSQL: []string{
			`CREATE TABLE app.cmp_src (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			   name varchar(100) NOT NULL, email varchar(255), qty bigint NOT NULL DEFAULT 1,
			   "Odd Col" varchar(10), created timestamptz DEFAULT CURRENT_TIMESTAMP)`,
			`CREATE INDEX cmp_src_name ON app.cmp_src (name)`,
			`CREATE UNIQUE INDEX cmp_src_email ON app.cmp_src (email)`,
			`COMMENT ON TABLE app.cmp_src IS 'it''s the source'`,
			`COMMENT ON COLUMN app.cmp_src.name IS 'who'`,
			`CREATE TABLE app.cmp_dst (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			   name varchar(50), qty int NOT NULL DEFAULT 0, legacy int)`,
			`CREATE INDEX cmp_legacy ON app.cmp_dst (legacy)`,
			`CREATE INDEX cmp_dst_name ON app.cmp_dst (name, qty)`,
		},
		DataCompareSQL: []string{
			"CREATE TABLE app.dat_src (id BIGINT PRIMARY KEY, name VARCHAR(50) NOT NULL, note TEXT, price NUMERIC(10,2), seen_at TIMESTAMP)",
			"CREATE TABLE app.dat_dst (id BIGINT PRIMARY KEY, name VARCHAR(50) NOT NULL, note TEXT, price NUMERIC(10,2), seen_at TIMESTAMP)",
			`INSERT INTO app.dat_src VALUES (1, 'same', 'x', 1.50, '2026-01-02 03:04:05'), (2, '李雷', '', NULL, NULL),
				(3, 'it''s', 'back\slash', 2.00, '2026-01-02 03:04:05'), (5, 'new', NULL, 9.99, NULL)`,
			`INSERT INTO app.dat_dst VALUES (1, 'same', 'x', 1.50, '2026-01-02 03:04:05'), (2, '李雷', NULL, NULL, NULL),
				(3, 'its', 'back\slash', 2.00, '2026-01-02 03:04:06'), (4, 'gone', NULL, NULL, NULL)`,
		},
	})
}
