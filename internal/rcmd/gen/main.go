//go:build ignore

// Command gen writes internal/rcmd/commands_gen.go from a running Redis
// server's COMMAND INFO and COMMAND DOCS:
//
//	docker run -d --rm -p 6390:6379 redis:7.4
//	go run internal/rcmd/gen/main.go -addr localhost:6390 > internal/rcmd/commands_gen.go
//	gofumpt -w internal/rcmd/commands_gen.go
//
// Only the server's own commands are kept (COMMAND DOCS has no module).
package main

import (
	"context"
	"flag"
	"fmt"
	"log"
	"os"
	"slices"
	"strings"

	"github.com/redis/go-redis/v9"
)

type command struct {
	Name, Args, Summary, Group string
	Flags, ACL                 []string
	First, Last, Step          int64
	Subcommands                bool
}

func main() {
	addr := flag.String("addr", "localhost:6379", "Redis 7.4 server")
	flag.Parse()
	ctx := context.Background()
	rc := redis.NewClient(&redis.Options{Addr: *addr, Protocol: 2})
	defer rc.Close()

	version := field(must(rc.Info(ctx, "server").Result()), "redis_version")
	infos := must(rc.Do(ctx, "COMMAND").Slice())
	docs := pairs(must(rc.Do(ctx, "COMMAND", "DOCS").Slice()))

	var out []command
	for _, raw := range infos {
		info := raw.([]any)
		name := info[0].(string)
		doc, ok := docs[name]
		if !ok || doc["module"] != nil {
			continue
		}
		out = append(out, build(info, doc))
		subDocs := pairs(list(doc["subcommands"]))
		for _, sraw := range list(info[9]) {
			sinfo := sraw.([]any)
			sname := sinfo[0].(string)
			out = append(out, build(sinfo, subDocs[sname]))
		}
	}
	slices.SortFunc(out, func(a, b command) int { return strings.Compare(a.Name, b.Name) })

	w := os.Stdout
	fmt.Fprintf(w, "// Code generated by internal/rcmd/gen from Redis %s; DO NOT EDIT.\n", version)
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "// Regenerate against a redis:7.4 container:")
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "//\tgo run internal/rcmd/gen/main.go -addr localhost:6390 > internal/rcmd/commands_gen.go")
	fmt.Fprintln(w, "\npackage rcmd\n\nvar commandTable = []Command{")
	for _, c := range out {
		fmt.Fprintf(w, "\t{Name: %q, Args: %q, Summary: %q, Group: %q, Flags: %#v, ACL: %#v, FirstKey: %d, LastKey: %d, Step: %d, Subcommands: %v},\n",
			c.Name, c.Args, c.Summary, c.Group, c.Flags, c.ACL, c.First, c.Last, c.Step, c.Subcommands)
	}
	fmt.Fprintln(w, "}")
}

func build(info []any, doc map[string]any) command {
	name := strings.ToUpper(strings.ReplaceAll(info[0].(string), "|", " "))
	c := command{
		Name:        name,
		Summary:     str(doc["summary"]),
		Group:       str(doc["group"]),
		Flags:       strs(info[2]),
		First:       info[3].(int64),
		Last:        info[4].(int64),
		Step:        info[5].(int64),
		Subcommands: len(list(info[9])) > 0,
	}
	for _, a := range strs(info[6]) {
		c.ACL = append(c.ACL, strings.TrimPrefix(a, "@"))
	}
	var parts []string
	for _, a := range list(doc["arguments"]) {
		parts = append(parts, render(pairsOf(a)))
	}
	c.Args = strings.Join(parts, " ")
	if c.Flags == nil {
		c.Flags = []string{}
	}
	if c.ACL == nil {
		c.ACL = []string{}
	}
	return c
}

// render writes one argument the way the Redis docs do: [optional],
// repeated ..., a|b for oneof, the token in front.
func render(a map[string]any) string {
	flags := strs(a["flags"])
	token := str(a["token"])
	var base string
	switch str(a["type"]) {
	case "pure-token":
		base, token = token, ""
		if base == "" {
			base = `""`
		}
	case "block", "oneof":
		var kids []string
		for _, k := range list(a["arguments"]) {
			kids = append(kids, render(pairsOf(k)))
		}
		sep := " "
		if str(a["type"]) == "oneof" {
			sep = "|"
		}
		base = strings.Join(kids, sep)
		if !slices.Contains(flags, "optional") && token != "" && len(kids) > 1 {
			base = "(" + base + ")"
		}
	default:
		base = str(a["display_text"])
		if base == "" {
			base = str(a["name"])
		}
	}
	one := base
	if token != "" {
		one = token + " " + base
	}
	s := one
	switch {
	case slices.Contains(flags, "multiple_token"):
		s = one + " [" + one + " ...]"
	case slices.Contains(flags, "multiple"):
		if token != "" {
			s = token + " " + base + " [" + base + " ...]"
		} else {
			s = base + " [" + base + " ...]"
		}
	}
	if slices.Contains(flags, "optional") {
		s = "[" + s + "]"
	}
	return s
}

func pairs(v []any) map[string]map[string]any {
	out := map[string]map[string]any{}
	for i := 0; i+1 < len(v); i += 2 {
		out[v[i].(string)] = pairsOf(v[i+1])
	}
	return out
}

func pairsOf(v any) map[string]any {
	out := map[string]any{}
	l := list(v)
	for i := 0; i+1 < len(l); i += 2 {
		out[l[i].(string)] = l[i+1]
	}
	return out
}

func list(v any) []any {
	l, _ := v.([]any)
	return l
}

func str(v any) string {
	s, _ := v.(string)
	return s
}

func strs(v any) []string {
	var out []string
	for _, x := range list(v) {
		out = append(out, fmt.Sprint(x))
	}
	return out
}

func field(info, name string) string {
	for line := range strings.SplitSeq(info, "\n") {
		if v, ok := strings.CutPrefix(strings.TrimSpace(line), name+":"); ok {
			return v
		}
	}
	return ""
}

func must[T any](v T, err error) T {
	if err != nil {
		log.Fatal(err)
	}
	return v
}
